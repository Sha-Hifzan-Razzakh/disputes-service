"""Single source for the service level objectives (T25.5). Generates ops/alerts/slo.rules.yml:

    uv run python ops/slo/slos.py            # write
    uv run python ops/slo/slos.py --check    # fail if the committed file is stale (CI)

Multi-window, multi-burn-rate alerts (Google SRE workbook, ch. 5): page when the 28-day budget would be gone in
~2 days (14.4x over 1h and 5m) or ~5 days (6x over 6h and 30m); ticket at 3x (1d/2h) and 1x (3d/6h).
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

RUNBOOK = "https://github.com/Sha-Hifzan-Razzakh/disputes-service/blob/main/docs/runbook.md"
OUT = Path(__file__).resolve().parents[1] / "alerts" / "slo.rules.yml"


@dataclass(frozen=True)
class Slo:
    name: str
    objective: float  # fraction of good events over 28 days
    description: str
    bad: str  # PromQL rate of bad events over [{w}]
    total: str  # PromQL rate of all events over [{w}]
    anchor: str  # runbook section


START = 'http_target="/v2/disputes/{{dispute_id}}/resolutions",http_method="POST"'

SLOS = [
    Slo(
        "api_availability",
        0.995,
        "/v2 requests answered without a 5xx",
        'sum(rate(http_server_duration_milliseconds_count{{http_target=~"/v2/.*",http_status_code=~"5.."}}[{w}]))',
        'sum(rate(http_server_duration_milliseconds_count{{http_target=~"/v2/.*"}}[{w}]))',
        "slo-api-availability",
    ),
    Slo(
        "start_latency",
        0.95,
        "resolution starts answered within 2.5 s (spec: p95 start <= 3 s with the rules drafter)",
        f"sum(rate(http_server_duration_milliseconds_count{{{{{START}}}}}[{{w}}]))"
        f' - sum(rate(http_server_duration_milliseconds_bucket{{{{{START},le="2500"}}}}[{{w}}]))',
        f"sum(rate(http_server_duration_milliseconds_count{{{{{START}}}}}[{{w}}]))",
        "slo-start-latency",
    ),
    Slo(
        "execution_success",
        0.99,
        "approved refunds and representments that executed",
        'sum(rate(resolution_outcomes_total{{outcome="EXECUTION_FAILED"}}[{w}]))',
        'sum(rate(resolution_outcomes_total{{outcome=~"REFUNDED|PARTIALLY_REFUNDED|REPRESENTED|EXECUTION_FAILED"}}[{w}]))',
        "slo-execution-success",
    ),
]

WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
BURNS = [  # (severity, burn factor, long window, short window)
    ("page", 14.4, "1h", "5m"),
    ("page", 6.0, "6h", "30m"),
    ("ticket", 3.0, "1d", "2h"),
    ("ticket", 1.0, "3d", "6h"),
]


def rules() -> dict:
    groups = []
    for s in SLOS:
        rec = [
            {
                "record": f"slo:{s.name}:error_ratio_{w}",
                "expr": f"({s.bad.format(w=w)}) / clamp_min({s.total.format(w=w)}, 1e-9)",
                "labels": {"slo": s.name},
            }
            for w in WINDOWS
        ]
        budget = round(1 - s.objective, 6)
        alerts = []
        for sev, burn, long, short in BURNS:
            alerts.append(
                {
                    "alert": f"SloBurn_{s.name}_{long}",
                    "expr": f"slo:{s.name}:error_ratio_{long} > ({burn} * {budget})"
                    f" and slo:{s.name}:error_ratio_{short} > ({burn} * {budget})",
                    "labels": {"severity": sev, "slo": s.name},
                    "annotations": {
                        "summary": f"{s.description}: error budget burning {burn}x ({long}/{short} windows)",
                        "runbook_url": f"{RUNBOOK}#{s.anchor}",
                    },
                }
            )
        groups.append({"name": f"slo-{s.name}", "rules": rec + alerts})
    return {"groups": groups}


def render() -> str:
    head = "# GENERATED by ops/slo/slos.py — edit the SLOs there, then run it.\n"
    return head + yaml.safe_dump(rules(), sort_keys=False, width=200)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run python ops/slo/slos.py")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT} ({len(SLOS)} SLOs)")
